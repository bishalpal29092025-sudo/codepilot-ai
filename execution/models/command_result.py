"""
Command execution result models.

Represents the output of a single shell command
executed by the Execution Engine.
"""

from __future__ import annotations

from pydantic import BaseModel, Field


class CommandResult(BaseModel):
    """
    Stores the result of a command execution.
    """

    command: str = Field(
        ...,
        description="Executed shell command.",
    )

    success: bool = Field(
        default=False,
        description="Whether command executed successfully.",
    )

    exit_code: int = Field(
        default=-1,
        description="Process exit code.",
    )

    stdout: str = Field(
        default="",
        description="Standard output generated by command.",
    )

    stderr: str = Field(
        default="",
        description="Error output generated by command.",
    )

    duration: float = Field(
        default=0.0,
        description="Execution duration in seconds.",
    )