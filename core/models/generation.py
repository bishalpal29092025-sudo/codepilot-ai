class GenerationContext(ImmutableModel):
    """
    Complete immutable context required to generate source code.

    This model acts as the contract between the Planning and Generation
    stages. Every component in the Generation package should operate on
    this model instead of receiving individual parameters.

    Retry / attempt state is intentionally omitted — that belongs to
    the execution or generator layer, not the generation context.
    """

    repository: RepositoryContext = Field(
        ...,
        description="Repository context.",
    )

    project: ProjectContext = Field(
        ...,
        description="Project context.",
    )

    task: TaskContext = Field(
        ...,
        description="Current implementation task.",
    )

    dependencies: DependencyContext = Field(
        ...,
        description="Dependency information.",
    )

    target_files: list[str] = Field(
        default_factory=list,
        description="Files expected to be created or modified.",
    )

    read_only_files: list[str] = Field(
        default_factory=list,
        description="Files that must never be modified.",
    )

    additional_instructions: list[str] = Field(
        default_factory=list,
        description="Extra instructions supplied to the generator.",
    )

    metadata: dict[str, Any] = Field(
        default_factory=dict,
        description="Additional generation metadata.",
    )

    @property
    def frameworks(self) -> list[str]:
        """
        Shortcut to repository frameworks.
        """
        return self.repository.frameworks

    @property
    def language(self) -> ProgrammingLanguage | str:
        """
        Primary project language.
        """
        return self.repository.primary_language

    @property
    def project_name(self) -> str:
        """
        Project name.
        """
        return self.project.name

    @property
    def task_title(self) -> str:
        """
        Current task title.
        """
        return self.task.title

    @property
    def task_description(self) -> str:
        """
        Current task description.
        """
        return self.task.description


