class GeneratedFile(ImmutableModel):
    """
    Represents a file generated or modified during code generation.
    """

    path: str = Field(
        ...,
        description="Repository-relative file path.",
    )

    language: str = Field(
        ...,
        description="Programming language of the file contents.",
    )

    operation: FileOperation = Field(
        default=FileOperation.CREATE,
        description="Operation performed on the file.",
    )

    content: str = Field(
        ...,
        description="Complete file contents.",
    )

    reason: str | None = Field(
        default=None,
        description="Reason why the file was generated or modified.",
    )

    checksum: str | None = Field(
        default=None,
        description="Optional content checksum (e.g. SHA-256).",
    )

    size: int = Field(
        default=0,
        ge=0,
        description="Content size in bytes.",
    )

    encoding: str = Field(
        default="utf-8",
        description="Text encoding used for the file.",
    )

    newline: str = Field(
        default="\n",
        description="Newline convention used in the file.",
    )

    metadata: dict[str, Any] = Field(
        default_factory=dict,
        description="Additional file metadata.",
    )

    @property
    def is_new_file(self) -> bool:
        """Whether the file is newly created."""
        return self.operation == FileOperation.CREATE

    @property
    def is_modified(self) -> bool:
        """Whether the file updates an existing file."""
        return self.operation == FileOperation.UPDATE

    @property
    def is_deleted(self) -> bool:
        """Whether the file should be deleted."""
        return self.operation == FileOperation.DELETE

    @property
    def filename(self) -> str:
        """Return the filename without directories."""
        return PurePosixPath(self.path).name

    @property
    def extension(self) -> str:
        """Return the file extension (including the leading dot)."""
        return PurePosixPath(self.path).suffix


class GenerationStatistics(ImmutableModel):
    """
    Statistics collected during generation.
    """

    files_created: int = Field(default=0, ge=0)
    files_updated: int = Field(default=0, ge=0)
    files_deleted: int = Field(default=0, ge=0)

    prompt_tokens: int = Field(default=0, ge=0)
    completion_tokens: int = Field(default=0, ge=0)
    total_tokens: int = Field(default=0, ge=0)

    generation_time: float = Field(
        default=0.0,
        ge=0.0,
        description="Generation time in seconds.",
    )

    @model_validator(mode="after")
    def validate_token_totals(self) -> Self:
        expected = self.prompt_tokens + self.completion_tokens
        if self.total_tokens != expected:
            raise ValueError(
                f"total_tokens ({self.total_tokens}) must equal "
                f"prompt_tokens + completion_tokens ({expected})"
            )
        return self

    @property
    def total_files(self) -> int:
        return (
            self.files_created
            + self.files_updated
            + self.files_deleted
        )


class GenerationResult(ImmutableModel):
    """
    Final output returned by the Generation package.
    """

    success: bool = Field(
        ...,
        description="Whether generation completed successfully.",
    )

    status: GenerationStatus = Field(
        default=GenerationStatus.COMPLETED,
        description="Generation status.",
    )

    provider: ProviderType = Field(
        ...,
        description="Provider used for generation.",
    )

    files: list[GeneratedFile] = Field(
        default_factory=list,
        description="Generated files.",
    )

    warnings: list[str] = Field(
        default_factory=list,
        description="Generation warnings.",
    )

    errors: list[str] = Field(
        default_factory=list,
        description="Generation errors.",
    )

    statistics: GenerationStatistics = Field(
        default_factory=GenerationStatistics,
        description="Generation statistics.",
    )

    metadata: dict[str, Any] = Field(
        default_factory=dict,
        description="Additional metadata.",
    )

    @model_validator(mode="after")
    def validate_status_consistency(self) -> Self:
        if self.success and self.status == GenerationStatus.FAILED:
            raise ValueError(
                "success=True is inconsistent with status=FAILED"
            )
        if not self.success and self.status not in (
            GenerationStatus.FAILED,
            GenerationStatus.PENDING,
            GenerationStatus.RUNNING,
        ):
            raise ValueError(
                "success=False requires a non-COMPLETED status "
                f"(got {self.status!r})"
            )
        return self

    @classmethod
    def success_result(
        cls,
        provider: ProviderType,
        files: list[GeneratedFile] | None = None,
        warnings: list[str] | None = None,
        statistics: GenerationStatistics | None = None,
        metadata: dict[str, Any] | None = None,
    ) -> GenerationResult:
        """
        Factory for a successful generation result.
        """
        return cls(
            success=True,
            status=GenerationStatus.COMPLETED,
            provider=provider,
            files=files or [],
            warnings=warnings or [],
            errors=[],
            statistics=statistics or GenerationStatistics(),
            metadata=metadata or {},
        )

    @classmethod
    def failure_result(
        cls,
        provider: ProviderType,
        errors: list[str],
        files: list[GeneratedFile] | None = None,
        warnings: list[str] | None = None,
        statistics: GenerationStatistics | None = None,
        metadata: dict[str, Any] | None = None,
    ) -> GenerationResult:
        """
        Factory for a failed generation result.
        """
        return cls(
            success=False,
            status=GenerationStatus.FAILED,
            provider=provider,
            files=files or [],
            warnings=warnings or [],
            errors=errors,
            statistics=statistics or GenerationStatistics(),
            metadata=metadata or {},
        )

    @property
    def generated_files(self) -> list[GeneratedFile]:
        return [
            file
            for file in self.files
            if file.operation == FileOperation.CREATE
        ]

    @property
    def modified_files(self) -> list[GeneratedFile]:
        return [
            file
            for file in self.files
            if file.operation == FileOperation.UPDATE
        ]

    @property
    def deleted_files(self) -> list[GeneratedFile]:
        return [
            file
            for file in self.files
            if file.operation == FileOperation.DELETE
        ]

    @property
    def file_count(self) -> int:
        return len(self.files)

    @property
    def has_errors(self) -> bool:
        return bool(self.errors)

    @property
    def has_warnings(self) -> bool:
        return bool(self.warnings)


