"""
Generation domain models.

These models define the immutable domain objects shared throughout the
Generation package. They represent the contract between the Planning,
Generation, Verification, and Execution stages of the CodePilot AI pipeline.

The models in this module contain no business logic. They only describe
the structure of the data exchanged between components.
"""

from __future__ import annotations

from enum import StrEnum
from pathlib import PurePosixPath
from typing import Any, Self

from pydantic import BaseModel, ConfigDict, Field, model_validator


# ============================================================================
# Enums
# ============================================================================


class GenerationStatus(StrEnum):
    """
    Represents the lifecycle state of a generation request.
    """

    PENDING = "pending"
    RUNNING = "running"
    COMPLETED = "completed"
    FAILED = "failed"


